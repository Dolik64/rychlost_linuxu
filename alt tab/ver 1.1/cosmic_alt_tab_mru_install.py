def run(argv, **kwargs):
    return subprocess.run([str(x) for x in argv], check=True, **kwargs)


def status():
    return subprocess.run(['systemctl', '--user', 'is-active', '--quiet', SERVICE]).returncode == 0


def unpack(destination):
    data = base64.b64decode(PAYLOAD)
    if hashlib.sha256(data).hexdigest() != PAYLOAD_SHA256:
        raise RuntimeError('Kontrolni soucet zdroju nesouhlasi. Stahni instalator znovu.')
    destination = Path(destination).resolve()
    if destination.exists() and any(destination.iterdir()):
        raise RuntimeError(f'Cilova slozka musi byt prazdna: {destination}')
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as archive:
        # Only bundled regular files/directories; no links, devices or path traversal.
        for member in archive.getmembers():
            relative = Path(member.name)
            if relative.is_absolute() or '..' in relative.parts or not (member.isfile() or member.isdir()):
                raise RuntimeError('Neplatna polozka archivu')
            target = destination / relative
            if member.isdir():
                target.mkdir(parents=True, exist_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                with archive.extractfile(member) as source, target.open('wb') as output:
                    shutil.copyfileobj(source, output)
                target.chmod(member.mode & 0o777)
    return destination


def atomic_bytes(path, data, mode):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as output:
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    finally:
        if os.path.lexists(tmp):
            os.unlink(tmp)


def backup(paths):
    folder = BASE / 'backups' / datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
    folder.mkdir(parents=True, mode=0o700)
    items = []
    for i, target in enumerate(paths):
        item = {'path': str(target), 'kind': 'missing'}
        if target.is_symlink():
            item.update(kind='symlink', link=os.readlink(target))
        elif target.is_file():
            name = str(i) + '.backup'
            shutil.copy2(target, folder / name)
            item.update(kind='file', file=name, mode=target.stat().st_mode & 0o777)
        elif target.exists():
            raise RuntimeError(f'Neocekavany typ cile: {target}')
        items.append(item)
    manifest = {'items': items, 'service_was_active': status()}
    (folder / 'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    return folder


def restore(folder):
    manifest = json.loads((folder / 'manifest.json').read_text(encoding='utf-8'))
    # Only paths owned by this installer are accepted from a local backup manifest.
    expected = {str(x) for x in [BIN, UNIT, START, AUTOSTART]}
    if {item['path'] for item in manifest['items']} != expected:
        raise RuntimeError('Zaloha neodpovida teto instalaci.')
    for item in manifest['items']:
        if item['kind'] == 'file' and not (folder / item['file']).is_file():
            raise RuntimeError('V zaloze chybi soubor; obnova nebyla zahajena.')
    subprocess.run(['systemctl', '--user', 'stop', SERVICE], check=False)
    for item in manifest['items']:
        target = Path(item['path'])
        if item['kind'] == 'file':
            atomic_bytes(target, (folder / item['file']).read_bytes(), item['mode'])
        elif item['kind'] == 'symlink':
            target.unlink(missing_ok=True)
            target.symlink_to(item['link'])
        else:
            target.unlink(missing_ok=True)
    run(['systemctl', '--user', 'daemon-reload'])
    if manifest['service_was_active']:
        run(['systemctl', '--user', 'start', SERVICE])
    print('Predchozi instalace byla obnovena.', flush=True)


def import_environment():
    names = [name for name in ['WAYLAND_DISPLAY', 'DISPLAY', 'XDG_CURRENT_DESKTOP', 'XDG_SESSION_TYPE'] if name in os.environ]
    if names:
        run(['systemctl', '--user', 'import-environment', *names])


def desktop_quote(value):
    # Desktop Entry Exec has its own quoting, plus '%' field codes.
    value = value.replace('%', '%%')
    for character in ['\\', '"', '`', '$']:
        value = value.replace(character, '\\' + character)
    # The .desktop value parser consumes backslash escaping before Exec parsing.
    value = value.replace('\\', '\\\\')
    return '"' + value + '"'


def install():
    if os.geteuid() == 0:
        raise RuntimeError('Spust instalator jako svuj bezny uzivatel, BEZ sudo.')
    if not os.environ.get('WAYLAND_DISPLAY') or not os.environ.get('XDG_RUNTIME_DIR'):
        raise RuntimeError('Spust instalator v terminalu uvnitr prihlaseneho COSMIC.')
    if not BIN.is_file():
        raise RuntimeError(f'Puvodni prepinac nebyl nalezen: {BIN}. Tento instalator upravuje existujici instalaci.')
    cargo = shutil.which('cargo')
    if not cargo and (Path.home() / '.cargo/bin/cargo').is_file():
        cargo = str(Path.home() / '.cargo/bin/cargo')
    if not cargo:
        raise RuntimeError('Chybi cargo/Rust. Pouzij stejne prostredi jako pri kompilaci puvodniho prepinace.')
    pkgconfig = shutil.which('pkg-config')
    if not pkgconfig or subprocess.run([pkgconfig, '--exists', 'wayland-client', 'xkbcommon']).returncode:
        raise RuntimeError('Chybi vyvojove knihovny. Nejprve spust: sudo apt install build-essential pkg-config libwayland-dev libxkbcommon-dev')
    run(['systemctl', '--user', 'show-environment'], stdout=subprocess.DEVNULL)
    print('1/4 Rozbaluji upravene zdroje. Dosavadni instalace zatim bezi beze zmen.', flush=True)
    source = unpack(BASE / 'builds' / datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f'))
    env = os.environ.copy()
    env['PATH'] = str(Path(cargo).parent) + os.pathsep + env.get('PATH', '')
    env['CARGO_TARGET_DIR'] = str(Path.home() / '.cache/cosmic-alt-tab-mru/target')
    env.setdefault('CARGO_BUILD_JOBS', '4')
    print('2/4 Kompiluji a spoustim testy. Prvni sestaveni muze trvat nekolik minut.', flush=True)
    run([cargo, 'test', '--locked', '--bin', 'cosmic-ext-app-switcher'], cwd=source, env=env)
    run([cargo, 'build', '--locked', '--release', '--bin', 'cosmic-ext-app-switcher'], cwd=source, env=env)
    new_binary = Path(env['CARGO_TARGET_DIR']) / 'release/cosmic-ext-app-switcher'
    run([new_binary, '--check-compat'])
    print('3/4 Vytvarim zalohu a instaluji prepinac s historii.', flush=True)
    folder = backup([BIN, UNIT, START, AUTOSTART])
    try:
        subprocess.run(['systemctl', '--user', 'stop', SERVICE], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        atomic_bytes(BIN, new_binary.read_bytes(), 0o755)
        unit = '''[Unit]
Description=COSMIC Alt-Tab per-window MRU history
PartOf=graphical-session.target
After=graphical-session.target

[Service]
Type=simple
ExecStart="%h/.local/bin/cosmic-ext-app-switcher" --daemon
Restart=on-failure
RestartSec=2
UMask=0077
'''
        atomic_bytes(UNIT, unit.encode(), 0o644)
        # XDG autostart runs inside each new graphical login with the correct
        # Wayland environment. No early boot service with stale session variables.
        starter = '''#!/bin/sh
set -eu
[ -n "${WAYLAND_DISPLAY:-}" ] || exit 0
systemctl --user import-environment WAYLAND_DISPLAY
[ -z "${DISPLAY:-}" ] || systemctl --user import-environment DISPLAY
systemctl --user restart cosmic-ext-app-switcher-mru.service
'''
        atomic_bytes(START, starter.encode(), 0o755)
        desktop = '[Desktop Entry]\nType=Application\nName=COSMIC Alt-Tab MRU history\nExec=' + desktop_quote(str(START)) + '\nTerminal=false\nOnlyShowIn=COSMIC;\n'
        atomic_bytes(AUTOSTART, desktop.encode(), 0o644)
        run(['systemctl', '--user', 'daemon-reload'])
        import_environment()
        run(['systemctl', '--user', 'start', SERVICE])
        print('4/4 Kontroluji spojeni s novou sluzbou.', flush=True)
        deadline = time.monotonic() + 15
        while True:
            result = subprocess.run([BIN, '--mru-check'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            if result.returncode == 0:
                break
            if time.monotonic() >= deadline:
                subprocess.run(['journalctl', '--user', '-u', SERVICE, '-n', '30', '--no-pager'])
                raise RuntimeError('Sluzba se nespustila; obnovuji puvodni instalaci.')
            time.sleep(0.2)
        atomic_bytes(BASE / 'last-backup', (str(folder) + '\n').encode(), 0o600)
    except BaseException:
        restore(folder)
        raise
    print('\nHOTOVO. Historie se od teto chvile sbira automaticky.')
    print('Zkus mysi: Nastaveni -> Firefox. Pak kratke Alt+Tab: zpet do Nastaveni.')
    print('Sipky, Alt+Shift+Tab, Enter a Escape zustavaji k dispozici.')
    print('Po startu sluzby je starsi historie neznama; postupne aktivuj otevrena okna.')
    print('Zaloha:', folder)
    print('Zdrojovy kod:', source)
    print('Diagnostika:', str(BIN), '--mru-list')
    print('Obnova: python3', shlex.quote(str(Path(__file__).resolve())), '--rollback')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--rollback', action='store_true')
    group.add_argument('--extract-only', type=Path)
    args = parser.parse_args()
    if args.extract_only:
        print(unpack(args.extract_only))
        return
    if os.geteuid() == 0:
        raise RuntimeError('Spust BEZ sudo, pod svym beznym uzivatelem.')
    BASE.mkdir(parents=True, exist_ok=True)
    with (BASE / 'installer.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        if args.rollback:
            marker = BASE / 'last-backup'
            if not marker.is_file():
                raise RuntimeError('Nebyla nalezena zaloha z uspesne instalace.')
            restore(Path(marker.read_text().strip()))
            marker.unlink()
        else:
            install()


if __name__ == '__main__':
    try:
        main()
    except (Exception, KeyboardInterrupt) as error:
        print('\nInstalace nebyla dokoncena:', error, file=sys.stderr)
        raise SystemExit(1)
